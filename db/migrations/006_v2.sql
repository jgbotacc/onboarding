CREATE TABLE IF NOT EXISTS looks (
  id TEXT PRIMARY KEY, session_id TEXT NOT NULL, round INTEGER NOT NULL, url TEXT NOT NULL,
  title TEXT, brief TEXT, selected INTEGER NOT NULL DEFAULT 0,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS consults (
  id TEXT PRIMARY KEY, session_id TEXT NOT NULL, status TEXT NOT NULL, card TEXT NOT NULL,
  approved_by TEXT, decided_at TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit (
  id INTEGER PRIMARY KEY AUTOINCREMENT, session_id TEXT, actor TEXT NOT NULL, action TEXT NOT NULL,
  target TEXT, details TEXT, at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS traces (
  id INTEGER PRIMARY KEY AUTOINCREMENT, session_id TEXT, step TEXT NOT NULL, model TEXT,
  ok INTEGER NOT NULL, latency_ms INTEGER, cost_sgd REAL, error TEXT, at TEXT
);
CREATE TABLE IF NOT EXISTS evals (
  id INTEGER PRIMARY KEY AUTOINCREMENT, kind TEXT NOT NULL, score REAL NOT NULL, n INTEGER NOT NULL,
  details TEXT, at TEXT DEFAULT CURRENT_TIMESTAMP
